it('shows a rejected save message and allows another save', async () => {
  const backend = fakeBackend({ setSpendingLimit: vi.fn().mockRejectedValue({ message: 'A build is running.' }) })
  const wrapper = screen(ConnectClaude, backend, { assistant })
  await flushPromises()
  await wrapper.get('#limit-day').setValue('20')
  await button(wrapper, 'Save the limit').trigger('click')
  await flushPromises()
  expect(wrapper.get('.alert-danger').text()).toBe('A build is running.')
  expect(button(wrapper, 'Save the limit').attributes('disabled')).toBeUndefined()
})
it('hides the fields and save button when loading the limit fails', async () => {
  const wrapper = screen(ConnectClaude, fakeBackend({ spendingLimit: vi.fn().mockRejectedValue({ message: 'The saved limit cannot be read.' }) }), { assistant })
  await flushPromises()
  expect(wrapper.get('.alert-danger').text()).toBe('The saved limit cannot be read.')
  expect(wrapper.find('#limit-day').exists()).toBe(false)
  expect(wrapper.find('#limit-step').exists()).toBe(false)
  expect(wrapper.findAll('button').some(item => item.text() === 'Save the limit')).toBe(false)
})
it('says the limit could not be read when loading fails without a message', async () => {
  const wrapper = screen(ConnectClaude, fakeBackend({ spendingLimit: vi.fn().mockRejectedValue(new Error('private detail')) }), { assistant })
  await flushPromises()
  expect(wrapper.get('.alert-danger').text()).toBe("Persona Builder couldn't read the limit. Close it and open it again.")
})
it('disables save while saving', async () => {
  const pending = deferred<{ dailyUsd: number; callUsd: number }>()
  const wrapper = screen(ConnectClaude, fakeBackend({ setSpendingLimit: vi.fn().mockReturnValue(pending.promise) }), { assistant })
  await flushPromises()
  await wrapper.get('#limit-day').setValue('20')
  await button(wrapper, 'Save the limit').trigger('click')
  expect(button(wrapper, 'Save the limit').attributes('disabled')).toBeDefined()
  pending.resolve({ dailyUsd: 20, callUsd: 5 })
  await flushPromises()
})
