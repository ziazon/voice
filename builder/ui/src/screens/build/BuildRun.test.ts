import { flushPromises } from '@vue/test-utils'
import { expect, it, vi } from 'vitest'
import { button, deferred, fakeBackend, screen } from '../../test-support'
import BuildRun from './BuildRun.vue'

const spend = { spentUsd: 3, dailyCapUsd: 50 }
const done = { answered: 1000, heldOut: 2, tested: false, spend }
it('shows live lines and spend, finishes with counts and emits running', async () => {
  const call = deferred<typeof done>()
  const backend = fakeBackend({ buildAssistant: vi.fn().mockImplementation((_r, progress) => { progress({ line: 'Reading your history', spend }); return call.promise }) })
  const wrapper = screen(BuildRun, backend, { slug: 'example' })
  await flushPromises()
  expect(wrapper.text()).toContain('Today, about $0.00 of the $50.00 daily limit, as Claude Code estimates it.')
  await button(wrapper, 'Build my assistant').trigger('click')
  expect(wrapper.get('ul[aria-live="polite"]').text()).toBe('Reading your history')
  expect(wrapper.text()).toContain('$3.00')
  call.resolve(done); await flushPromises()
  expect(wrapper.text()).toContain("Done. Your assistant is built from 1,000 answers to Claude's questions.")
  expect(wrapper.text()).toContain("There weren't enough answers kept aside")
  expect(button(wrapper, 'Build again').attributes('disabled')).toBeUndefined()
  expect(wrapper.emitted('running')).toEqual([[true], [false]])
  expect(wrapper.emitted('finished')).toHaveLength(1)
})
it('stops, keeps the lines and shows stopped failures as information', async () => {
  const call = deferred<typeof done>()
  const backend = fakeBackend({ buildAssistant: vi.fn().mockReturnValue(call.promise) })
  const wrapper = screen(BuildRun, backend, { slug: 'example' }); await flushPromises()
  await button(wrapper, 'Build my assistant').trigger('click')
  await button(wrapper, 'Stop').trigger('click')
  expect(backend.stopBuild).toHaveBeenCalledWith({ slug: 'example' })
  expect(button(wrapper, 'Stopping…').attributes('disabled')).toBeUndefined()
  await button(wrapper, 'Stopping…').trigger('click')
  expect(backend.stopBuild).toHaveBeenCalledTimes(2)
  call.reject({ message: 'Stopped safely.' }); await flushPromises()
  expect(wrapper.get('.alert-info').text()).toBe('Stopped safely.')
  expect(wrapper.emitted('running')).toEqual([[true], [false]])
})
it('shows the failure fallback and skips the untested sentence when tested', async () => {
  const backend = fakeBackend({ buildAssistant: vi.fn().mockRejectedValueOnce(new Error('private')).mockResolvedValueOnce({ ...done, tested: true }) })
  const wrapper = screen(BuildRun, backend, { slug: 'example' }); await flushPromises()
  await button(wrapper, 'Build my assistant').trigger('click'); await flushPromises()
  expect(wrapper.get('.alert-danger').text()).toContain('The build stopped before it finished')
  await button(wrapper, 'Build again').trigger('click'); await flushPromises()
  expect(wrapper.text()).not.toContain("There weren't enough answers kept aside")
})
it('rebuild merges first and does not build after a failed merge', async () => {
  const backend = fakeBackend({ mergeHistories: vi.fn().mockRejectedValue(new Error('private')) })
  const wrapper = screen(BuildRun, backend, { slug: 'example' }); await flushPromises()
  await wrapper.vm.rebuild(); await flushPromises()
  expect(backend.mergeHistories).toHaveBeenCalledWith({ slug: 'example' })
  expect(backend.buildAssistant).not.toHaveBeenCalled()
  expect(wrapper.get('.alert-danger').text()).toContain("couldn't put your history together")
})
it('locks navigation and prevents duplicate builds while rebuilding merges history', async () => {
  const merge = deferred<{ questions: number, heldOut: number, messages: number, duplicates: number, privateLeftOut: number }>()
  const backend = fakeBackend({ mergeHistories: vi.fn().mockReturnValue(merge.promise) })
  const wrapper = screen(BuildRun, backend, { slug: 'example' }); await flushPromises()
  const rebuilding = wrapper.vm.rebuild(); await flushPromises()
  expect(wrapper.emitted('running')).toEqual([[true]])
  expect(wrapper.text()).not.toContain('Build my assistant')
  await wrapper.vm.rebuild()
  expect(backend.mergeHistories).toHaveBeenCalledTimes(1)
  merge.resolve({ questions: 1, heldOut: 0, messages: 0, duplicates: 0, privateLeftOut: 0 })
  await rebuilding; await flushPromises()
  expect(backend.buildAssistant).toHaveBeenCalledTimes(1)
  expect(wrapper.emitted('running')).toEqual([[true], [false]])
})
it.each(['resolve', 'reject'] as const)('ignores a stale initial spend %s after build progress', async outcome => {
  const initial = deferred<typeof spend>()
  const call = deferred<typeof done>()
  const backend = fakeBackend({ spendToday: vi.fn().mockReturnValue(initial.promise), buildAssistant: vi.fn().mockImplementation((_request, progress) => { progress({ line: 'Reading your history', spend }); return call.promise }) })
  const wrapper = screen(BuildRun, backend, { slug: 'example' })
  await button(wrapper, 'Build my assistant').trigger('click')
  if (outcome === 'resolve') initial.resolve({ spentUsd: 0, dailyCapUsd: 50 })
  else initial.reject({ message: 'Outdated failure' })
  await flushPromises()
  expect(wrapper.text()).toContain('Today, about $3.00')
  expect(wrapper.text()).not.toContain('Outdated failure')
  call.resolve(done); await flushPromises()
})
it('does not start a build when stopped while putting history together', async () => {
  const merge = deferred<{ questions: number, heldOut: number, messages: number, duplicates: number, privateLeftOut: number }>()
  const backend = fakeBackend({ mergeHistories: vi.fn().mockReturnValue(merge.promise) })
  const wrapper = screen(BuildRun, backend, { slug: 'example' }); await flushPromises()
  const rebuilding = wrapper.vm.rebuild(); await flushPromises()
  await button(wrapper, 'Stop').trigger('click')
  merge.resolve({ questions: 1, heldOut: 0, messages: 0, duplicates: 0, privateLeftOut: 0 }); await rebuilding; await flushPromises()
  expect(backend.buildAssistant).not.toHaveBeenCalled()
  expect(wrapper.get('.alert-info').text()).toContain('Stopped. Your assistant is as it was before this build.')
  expect(wrapper.emitted('running')).toEqual([[true], [false]])
})
