import { flushPromises } from '@vue/test-utils'
import { expect, it, vi } from 'vitest'
import { button, deferred, fakeBackend, screen } from '../../test-support'
import Interview from './Interview.vue'
const questions = Array.from({ length: 20 }, (_, i) => ({ n: i + 1, kind: 'Work', question: `Question ${i + 1}?`, multiSelect: i === 0, recommended: 'A', options: ['A', 'B', 'C', 'D'].map(letter => ({ letter, label: `Option ${letter}`, description: `Description ${letter}` })) }))
const status = { answered: 10, thinBelow: 150, thinKinds: [], questions, answers: [], kept: false }
it('shows only the short line for enough history', async () => {
  const wrapper = screen(Interview, fakeBackend({ interviewStatus: vi.fn().mockResolvedValue({ ...status, answered: 150, questions: [] }) }), { slug: 'example' })
  await flushPromises()
  expect(wrapper.text()).toContain("Your history holds 150 answers to Claude's questions, enough to build from.")
  expect(wrapper.findAll('p').map(line => line.text())).toEqual(["Your history holds 150 answers to Claude's questions, enough to build from."])
  expect(wrapper.findAll('button')).toHaveLength(0)
})
it('names thin kinds in enough history and drafts a short interview', async () => {
  const short = { ...status, answered: 150, thinKinds: ['Scope', 'Go or no-go'], questions: questions.slice(0, 8) }
  const backend = fakeBackend({ interviewStatus: vi.fn().mockResolvedValue({ ...short, questions: [] }), draftInterview: vi.fn().mockResolvedValue(short) })
  const wrapper = screen(Interview, backend, { slug: 'example' }); await flushPromises()
  expect(wrapper.text()).toContain("Your history holds 150 answers to Claude's questions, enough to build from, but a few kinds of decision have fewer than five examples so far: Scope, Go or no-go. A few questions on each fills them out.")
  expect(wrapper.text()).not.toContain('Answering twenty questions fills it out.')
  await button(wrapper, 'Draft the questions').trigger('click'); await flushPromises()
  expect(backend.draftInterview).toHaveBeenCalledWith({ slug: 'example', replace: false })
  expect(wrapper.findAll('fieldset')).toHaveLength(4)
  expect(wrapper.text()).toContain('Questions 1–4 of 8')
})
it('drafts thin history with progress and disables the card', async () => {
  const draft = deferred<typeof status>()
  const backend = fakeBackend({ draftInterview: vi.fn().mockReturnValue(draft.promise) })
  const wrapper = screen(Interview, backend, { slug: 'example' }); await flushPromises()
  await button(wrapper, 'Draft the questions').trigger('click')
  expect(backend.draftInterview).toHaveBeenCalledWith({ slug: 'example', replace: false })
  expect(wrapper.get('[role="progressbar"]').attributes('aria-label')).toBe('Drafting')
  expect(button(wrapper, 'Drafting the questions…').attributes('disabled')).toBeDefined()
  draft.resolve(status); await flushPromises()
  expect(wrapper.findAll('fieldset')).toHaveLength(4)
})
it('pages four questions, saves every answer in option order, and keeps and rebuilds', async () => {
  const backend = fakeBackend({ interviewStatus: vi.fn().mockResolvedValue({ ...status, answers: [{ n: 2, picks: ['B'], ownWords: 'Saved words' }] }), saveInterviewAnswers: vi.fn().mockResolvedValue(status) })
  const wrapper = screen(Interview, backend, { slug: 'example' }); await flushPromises()
  expect(wrapper.findAll('fieldset')).toHaveLength(4)
  expect(wrapper.findAll('input[type="checkbox"]')).toHaveLength(4)
  expect(wrapper.findAll('input[type="radio"]')).toHaveLength(12)
  expect(wrapper.findAll('.badge').map(item => item.text())).toEqual(Array(4).fill('Suggested'))
  expect((wrapper.findAll('textarea')[1]!.element as HTMLTextAreaElement).value).toBe('Saved words')
  const options = wrapper.findAll('fieldset')[0]!.findAll('input')
  await options[2]!.setValue(true); await options[0]!.setValue(true)
  await wrapper.findAll('textarea')[0]!.setValue('My approach')
  await button(wrapper, 'Next').trigger('click'); await flushPromises()
  expect(backend.saveInterviewAnswers).toHaveBeenCalledWith({ slug: 'example', answers: expect.arrayContaining([{ n: 1, picks: ['A', 'C'], ownWords: 'My approach' }, { n: 2, picks: ['B'], ownWords: 'Saved words' }]) })
  expect(wrapper.text()).toContain('Questions 5–8 of 20')
  for (let page = 2; page < 5; page++) { await button(wrapper, 'Next').trigger('click'); await flushPromises() }
  await button(wrapper, 'Keep my answers').trigger('click'); await flushPromises()
  expect(backend.keepInterviewAnswers).toHaveBeenCalledWith({ slug: 'example' })
  expect(wrapper.text()).toContain('Kept 2 answers. 1 that looked private were left out.')
  await button(wrapper, 'Add them to your history and build again').trigger('click')
  expect(wrapper.emitted('rebuild')).toEqual([[]])
})
it('confirms replacement and failed saves keep the page', async () => {
  const backend = fakeBackend({ interviewStatus: vi.fn().mockResolvedValue(status), saveInterviewAnswers: vi.fn().mockRejectedValue(new Error('private')) })
  const wrapper = screen(Interview, backend, { slug: 'example' }); await flushPromises()
  await button(wrapper, 'Next').trigger('click'); await flushPromises()
  expect(wrapper.text()).toContain('Questions 1–4 of 20')
  expect(wrapper.get('.alert-danger').text()).toContain("couldn't save your answers")
  await button(wrapper, 'Draft different questions').trigger('click')
  expect(backend.draftInterview).not.toHaveBeenCalled()
  expect(wrapper.get('.alert-warning').text()).toContain('This replaces these questions and your answers to them.')
  await wrapper.get('.alert-warning button').trigger('click'); await flushPromises()
  expect(backend.draftInterview).toHaveBeenCalledWith({ slug: 'example', replace: true })
})
it('clears a kept result after edits or navigation and offers rebuilding only after keeping again', async () => {
  const backend = fakeBackend({ interviewStatus: vi.fn().mockResolvedValue(status), saveInterviewAnswers: vi.fn().mockResolvedValue(status) })
  const wrapper = screen(Interview, backend, { slug: 'example' }); await flushPromises()
  for (let page = 0; page < 4; page++) { await button(wrapper, 'Next').trigger('click'); await flushPromises() }
  await button(wrapper, 'Keep my answers').trigger('click'); await flushPromises()
  expect(wrapper.text()).toContain('Kept 2 answers.')
  await wrapper.findAll('textarea')[0]!.setValue('Updated words')
  expect(wrapper.text()).not.toContain('Kept 2 answers.')
  expect(wrapper.text()).not.toContain('Add them to your history and build again')
  await button(wrapper, 'Keep my answers').trigger('click'); await flushPromises()
  expect(wrapper.text()).toContain('Kept 2 answers.')
  await wrapper.findAll('input')[0]!.setValue(true)
  expect(wrapper.text()).not.toContain('Add them to your history and build again')
  await button(wrapper, 'Keep my answers').trigger('click'); await flushPromises()
  expect(wrapper.text()).toContain('Kept 2 answers.')
  await button(wrapper, 'Back').trigger('click'); await flushPromises()
  expect(wrapper.text()).not.toContain('Kept 2 answers.')
  expect(wrapper.text()).not.toContain('Add them to your history and build again')
  await button(wrapper, 'Next').trigger('click'); await flushPromises()
  await button(wrapper, 'Keep my answers').trigger('click'); await flushPromises()
  expect(wrapper.text()).toContain('Add them to your history and build again')
})
