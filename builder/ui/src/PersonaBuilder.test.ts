it('opens save without requiring permission and keeps steps five and six unavailable', async () => {
  const backend = fakeBackend({ listAssistants: vi.fn().mockResolvedValue([assistant]) })
  const wrapper = screen(PersonaBuilder, backend)
  await flushPromises()
  await button(wrapper, 'Open').trigger('click')
  await flushPromises()
  const items = wrapper.findAll('ol li')
  for (const item of items.slice(4, 6)) {
    expect(item.attributes('aria-disabled')).toBe('true')
    expect(item.text()).toContain('Not here yet')
  }
  const save = items[6]!
  expect(save.attributes('aria-disabled')).toBeUndefined()
  expect(save.get('button').attributes('disabled')).toBeUndefined()
  await save.get('button').trigger('click')
  await flushPromises()
  expect(wrapper.get('main h2').text()).toBe('Keep a copy')
  expect(wrapper.get('[aria-current="step"]').text()).toBe('Save')
  expect(backend.saveOptions).toHaveBeenCalledExactlyOnceWith({ slug: assistant.slug })
  expect(backend.agreeConsent).not.toHaveBeenCalled()
})

it('shows four save cards and preserves the forget message while resetting permission', async () => {
  const backend = fakeBackend({ listAssistants: vi.fn().mockResolvedValue([{ ...assistant, consent: { agreed: true, agreedOn: '2026-10-25' } }]), forgetPreview: vi.fn().mockResolvedValue({ files: 7 }) })
  const wrapper = screen(PersonaBuilder, backend)
  await flushPromises(); await button(wrapper, 'Open').trigger('click'); await flushPromises()
  await button(wrapper, 'Save').trigger('click'); await flushPromises()
  expect(wrapper.findAll('main h2').map(h => h.text())).toEqual(['Keep a copy', 'Use it in Claude Code', 'Use it in claude.ai', 'Forget what Example learned from'])
  await button(wrapper, 'Forget…').trigger('click'); await flushPromises()
  await button(wrapper, 'Delete these files').trigger('click'); await flushPromises()
  expect(wrapper.get('.alert-success').text()).toBe('Deleted 7 files.')
  expect(wrapper.findAll('ol li')[1]!.text()).toContain('Needs your permission first')
  expect(wrapper.findAll('ol li')[1]!.get('button').attributes('disabled')).toBeDefined()
  expect(backend.saveOptions).toHaveBeenCalledTimes(2)
  expect(backend.claudeCodeStatus).toHaveBeenCalledTimes(2)
  expect(backend.claudeAiFiles).toHaveBeenCalledTimes(2)
  await button(wrapper, 'Your permission').trigger('click'); await flushPromises()
  expect(wrapper.text()).not.toContain('You agreed on')
  expect(button(wrapper, 'I agree').exists()).toBe(true)
})

it('enables Your assistants after forgetting during an unsettled build', async () => {
  const backend = fakeBackend({
    listAssistants: vi.fn().mockResolvedValue([{ ...assistant, consent: { agreed: true, agreedOn: '2026-10-25' } }]),
    forgetPreview: vi.fn().mockResolvedValue({ files: 7 }),
    buildAssistant: vi.fn().mockImplementation(() => new Promise(() => {})),
  })
  const wrapper = screen(PersonaBuilder, backend)
  await flushPromises()
  await button(wrapper, 'Open').trigger('click'); await flushPromises()
  await button(wrapper, 'Build').trigger('click'); await flushPromises()
  await button(wrapper, 'Build my assistant').trigger('click'); await flushPromises()
  expect(backend.buildAssistant).toHaveBeenCalledExactlyOnceWith({ slug: assistant.slug }, expect.any(Function))
  expect(button(wrapper, 'Your assistants').attributes('disabled')).toBeDefined()
  expect(wrapper.text()).toContain('Stop the build first to choose another assistant.')
  await button(wrapper, 'Save').trigger('click'); await flushPromises()
  await button(wrapper, 'Forget…').trigger('click'); await flushPromises()
  await button(wrapper, 'Delete these files').trigger('click'); await flushPromises()
  expect(backend.forget).toHaveBeenCalledExactlyOnceWith({ slug: assistant.slug, files: 7 })
  expect(wrapper.find('ul[aria-live="polite"]').exists()).toBe(false)
  expect(button(wrapper, 'Your assistants').attributes('disabled')).toBeUndefined()
  expect(wrapper.text()).not.toContain('Stop the build first to choose another assistant.')
})

it('keeps build disabled until permission, opens from sources, and preserves running lines across steps', async () => {
  let progress: ((value: { line: string, spend: { spentUsd: number, dailyCapUsd: number } }) => void) | undefined
  const backend = fakeBackend({ listAssistants: vi.fn().mockResolvedValue([assistant]), buildAssistant: vi.fn().mockImplementation((_request, callback) => { progress = callback; return new Promise(() => {}) }) })
  const wrapper = screen(PersonaBuilder, backend); await flushPromises()
  await button(wrapper, 'Open').trigger('click'); await flushPromises()
  const build = button(wrapper, 'Build')
  expect(build.attributes('disabled')).toBeDefined()
  expect(wrapper.findAll('ol li')[3]!.text()).toContain('Needs your permission first')
  await button(wrapper, 'I agree').trigger('click'); await flushPromises()
  expect(button(wrapper, 'Build').attributes('disabled')).toBeUndefined()
  await button(wrapper, 'Next: your history').trigger('click'); await flushPromises()
  await button(wrapper, 'Next: build your assistant').trigger('click'); await flushPromises()
  expect(wrapper.get('main h2').text()).toBe('Build your assistant')
  await button(wrapper, 'Build my assistant').trigger('click')
  progress!({ line: 'Reading your history', spend: { spentUsd: 1, dailyCapUsd: 50 } }); await flushPromises()
  expect(button(wrapper, 'Your assistants').attributes('disabled')).toBeDefined()
  expect(wrapper.text()).toContain('Stop the build first to choose another assistant.')
  await button(wrapper, 'Your history').trigger('click'); await flushPromises()
  await button(wrapper, 'Build').trigger('click'); await flushPromises()
  expect(wrapper.get('ul[aria-live="polite"]').text()).toContain('Reading your history')
  expect(backend.buildAssistant).toHaveBeenCalledTimes(1)
})
